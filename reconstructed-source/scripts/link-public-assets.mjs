import {
  access,
  lstat,
  mkdir,
  readFile,
  rm,
  symlink,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const sourceRoot = fileURLToPath(new URL("../../public/", import.meta.url));
const projectRoot = fileURLToPath(new URL("../", import.meta.url));
const publicPath = path.join(projectRoot, "public");
const markerPath = path.join(publicPath, ".recovery-public-assets");
const marker = "Generated by scripts/link-public-assets.mjs\n";
const publicEntries = [
  "_headers",
  "brand",
  "dermatologists",
  "homepage",
  "icon.svg",
  "icons",
  "products",
];
const fonts = {
  "body.woff2": "_next/static/media/9e8bdbcdb204cea9-s.p.woff2",
  "display.woff2": "_next/static/media/47e08c75a96690df-s.p.woff2",
};

await access(sourceRoot);

try {
  const stat = await lstat(publicPath);
  if (stat.isSymbolicLink()) {
    await rm(publicPath);
  } else {
    let generated = false;
    try {
      generated = (await readFile(markerPath, "utf8")) === marker;
    } catch {
      generated = false;
    }
    if (!generated) {
      throw new Error(
        `${publicPath} exists and is not the generated public-assets directory`,
      );
    }
    await rm(publicPath, { recursive: true });
  }
} catch (error) {
  if (error?.code !== "ENOENT") {
    throw error;
  }
}

await mkdir(path.join(publicPath, "fonts"), { recursive: true });
await writeFile(markerPath, marker);

for (const entry of publicEntries) {
  const source = path.join(sourceRoot, entry);
  await access(source);
  await symlink(
    path.relative(publicPath, source),
    path.join(publicPath, entry),
  );
}

for (const [name, relativeSource] of Object.entries(fonts)) {
  const source = path.join(sourceRoot, relativeSource);
  await access(source);
  await symlink(
    path.relative(path.join(publicPath, "fonts"), source),
    path.join(publicPath, "fonts", name),
  );
}

console.log(
  `linked ${publicEntries.length} public asset entries and ${Object.keys(fonts).length} recovered fonts`,
);
